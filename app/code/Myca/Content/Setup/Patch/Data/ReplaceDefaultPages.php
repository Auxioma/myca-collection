<?php

declare(strict_types=1);

namespace Myca\Content\Setup\Patch\Data;

use Magento\Cms\Api\GetPageByIdentifierInterface;
use Magento\Cms\Api\PageRepositoryInterface;
use Magento\Framework\Exception\NoSuchEntityException;
use Magento\Framework\Filesystem\Driver\File;
use Magento\Framework\Setup\Patch\DataPatchInterface;
use Magento\Store\Model\Store;
use Magento\Framework\Setup\ModuleDataSetupInterface;
use Magento\Store\Model\StoreManagerInterface;

/**
 * Remplace les pages d'exemple de Magento, publiées en anglais : page 404 aux couleurs MYCA, page « cookies
 * désactivés » en français, et « Privacy and Cookie Policy » redirigée vers la politique de confidentialité.
 * Une page déjà modifiée par MYCA n'est pas touchée.
 */
class ReplaceDefaultPages implements DataPatchInterface
{
    public function __construct(
        private readonly GetPageByIdentifierInterface $getPageByIdentifier,
        private readonly PageRepositoryInterface $pageRepository,
        private readonly File $file,
        private readonly ModuleDataSetupInterface $moduleDataSetup,
        private readonly StoreManagerInterface $storeManager
    ) {
    }

    public function apply(): self
    {
        $this->replace('no-route', 'fine guess', 'Page introuvable', 'Page introuvable', 'no-route.html');
        $this->replace('enable-cookies', 'little pieces of data', 'Activer les cookies', 'Activer les cookies', 'enable-cookies.html');
        $this->redirectPrivacyPolicy();

        return $this;
    }

    private function replace(string $identifier, string $defaultMarker, string $title, string $heading, string $file): void
    {
        try {
            $page = $this->getPageByIdentifier->execute($identifier, Store::DEFAULT_STORE_ID);
        } catch (NoSuchEntityException) {
            return;
        }
        if (!str_contains((string) $page->getContent(), $defaultMarker)) {
            return;
        }
        $page->setTitle($title);
        $page->setContentHeading($heading);
        $page->setPageLayout('1column');
        $page->setContent($this->file->fileGetContents(__DIR__ . '/../../content/pages/' . $file));
        $this->pageRepository->save($page);
    }

    private function redirectPrivacyPolicy(): void
    {
        try {
            $page = $this->getPageByIdentifier->execute('privacy-policy-cookie-restriction-mode', Store::DEFAULT_STORE_ID);
        } catch (NoSuchEntityException) {
            return;
        }
        if (!str_contains((string) $page->getContent(), 'Please replace this text')) {
            return;
        }
        $this->pageRepository->delete($page);
        // Insertion ligne à ligne : UrlPersist::replace() effacerait les autres réécritures « custom ».
        $connection = $this->moduleDataSetup->getConnection();
        foreach ($this->storeManager->getStores() as $store) {
            $connection->insertOnDuplicate($this->moduleDataSetup->getTable('url_rewrite'), [
                'entity_type' => 'custom',
                'entity_id' => 0,
                'request_path' => 'privacy-policy-cookie-restriction-mode',
                'target_path' => 'confidentialite',
                'redirect_type' => 301,
                'store_id' => (int) $store->getId(),
                'is_autogenerated' => 0,
                'description' => 'Ancienne politique Magento (Myca_Content)',
            ], ['target_path', 'redirect_type']);
        }
    }

    public static function getDependencies(): array
    {
        return [CreateServicePages::class];
    }

    public function getAliases(): array
    {
        return [];
    }
}
