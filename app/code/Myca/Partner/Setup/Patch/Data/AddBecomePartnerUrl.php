<?php

declare(strict_types=1);

namespace Myca\Partner\Setup\Patch\Data;

use Magento\Framework\Setup\ModuleDataSetupInterface;
use Magento\Framework\Setup\Patch\DataPatchInterface;
use Magento\Store\Model\StoreManagerInterface;

/**
 * Adresse publique du formulaire P17 : /devenir-partenaire → candidature-partenaire/candidature.
 */
class AddBecomePartnerUrl implements DataPatchInterface
{
    public function __construct(
        private readonly ModuleDataSetupInterface $moduleDataSetup,
        private readonly StoreManagerInterface $storeManager
    ) {
    }

    public function apply(): self
    {
        $connection = $this->moduleDataSetup->getConnection();
        $table = $this->moduleDataSetup->getTable('url_rewrite');
        foreach ($this->storeManager->getStores() as $store) {
            $connection->insertOnDuplicate($table, [
                'entity_type' => 'custom',
                'entity_id' => 0,
                'request_path' => 'devenir-partenaire',
                'target_path' => 'candidature-partenaire/candidature',
                'redirect_type' => 0,
                'store_id' => (int) $store->getId(),
                'is_autogenerated' => 0,
                'description' => 'P17 Devenir partenaire (Myca_Partner)',
            ], ['target_path', 'redirect_type']);
        }

        return $this;
    }

    public static function getDependencies(): array
    {
        return [];
    }

    public function getAliases(): array
    {
        return [];
    }
}
